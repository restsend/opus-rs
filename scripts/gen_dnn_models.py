#!/usr/bin/env python3
"""Writes src/dnn/models/*.rs from the model data files of libopus 1.6.1.

Usage: python3 -I scripts/gen_dnn_models.py <opus-1.6.1 source dir> <out dir>

Each model module gets the constants of its `dnn/<model>_data.h`, the
layer struct and an `init` that does what the model's `init_*` function in
`dnn/<model>_data.c` does (`linear_init`/`conv2d_init` with the same array
names and sizes).
"""
import re
import sys
from pathlib import Path

MODELS = [
    # (file stem, C struct, Rust struct, C init)
    ("pitchdnn", "PitchDNN", "PitchDnn", "init_pitchdnn"),
    ("fargan", "FARGAN", "Fargan", "init_fargan"),
    ("plc", "PLCModel", "PlcModel", "init_plcmodel"),
    ("dred_rdovae_enc", "RDOVAEEnc", "RdovaeEnc", "init_rdovaeenc"),
    ("dred_rdovae_dec", "RDOVAEDec", "RdovaeDec", "init_rdovaedec"),
    ("lace", "LACELayers", "LaceLayers", "init_lacelayers"),
    ("nolace", "NOLACELayers", "NolaceLayers", "init_nolacelayers"),
    ("bbwenet", "BBWENETLayers", "BbwenetLayers", "init_bbwenetlayers"),
]

HEADER = """// Generated by scripts/gen_dnn_models.py from libopus 1.6.1
// dnn/{stem}_data.h and dnn/{stem}_data.c. Do not edit.
"""


def consts(text):
    out = []
    for m in re.finditer(r"^#define\s+([A-Z][A-Z0-9_]*)\s+(.+?)\s*$", text, re.M):
        name, val = m.group(1), m.group(2)
        if name.endswith("_H"):
            continue
        if re.fullmatch(r"-?[0-9]+\.[0-9]*(e-?[0-9]+)?f", val):
            out.append(f"pub const {name}: f32 = {val[:-1]};")
        elif re.fullmatch(r"[0-9 ()*+]+", val):
            out.append(f"pub const {name}: usize = {eval(val)};")
        else:
            raise SystemExit(f"unhandled define {name} {val}")
    return out


def arg(a):
    a = a.strip()
    if a == "NULL":
        return "None"
    if a.startswith('"'):
        return f"Some({a})"
    return a


def gen(src, stem, cstruct, rstruct, cinit):
    h = (src / f"dnn/{stem}_data.h").read_text()
    c = (src / f"dnn/{stem}_data.c").read_text()
    sm = re.search(r"(?:typedef )?struct(?: %s)? \{(.*?)\}" % cstruct, h, re.S)
    fields = re.findall(r"(LinearLayer|Conv2dLayer)\s+(\w+);", sm.group(1))
    body = re.search(r"int %s\([^)]*\) \{(.*?)\n\}" % cinit, c, re.S).group(1)
    inits = {}
    for m in re.finditer(r"(linear_init|conv2d_init)\(&model->(\w+), arrays, (.*?)\)\) return 1;", body):
        kind, field, args = m.groups()
        args = [arg(x) for x in args.split(",")]
        if kind == "linear_init":
            assert len(args) == 9, (field, args)
            inits[field] = f"list.linear({', '.join(args[:7])}, {args[7]}, {args[8]})?"
        else:
            assert len(args) == 6, (field, args)
            inits[field] = f"list.conv2d({', '.join(args)})?"
    assert set(inits) == {f for _, f in fields}, stem
    lines = [HEADER.format(stem=stem)]
    lines.append("#[allow(unused_imports)]\nuse crate::dnn::nnet::{Conv2dLayer, LinearLayer};")
    lines.append("use crate::dnn::weights::{WeightError, WeightList};\n")
    lines += consts(h)
    lines.append("")
    lines.append(f"/// libopus `{cstruct}`.")
    lines.append("#[derive(Clone, Copy, Debug, Default)]")
    lines.append(f"pub struct {rstruct}<'a> {{")
    for t, f in fields:
        lines.append(f"    pub {f}: {t}<'a>,")
    lines.append("}\n")
    lines.append(f"impl<'a> {rstruct}<'a> {{")
    lines.append(f"    /// libopus `{cinit}`.")
    lines.append(f"    pub fn init(list: &WeightList<'a>) -> Result<Self, WeightError> {{")
    lines.append("        Ok(Self {")
    for _, f in fields:
        lines.append(f"            {f}: {inits[f]},")
    lines.append("        })")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for stem, cs, rs, ci in MODELS:
        (out / f"{stem}.rs").write_text(gen(src, stem, cs, rs, ci))
    k = (src / "dnn/dred_rdovae_constants.h").read_text()
    (out / "dred_rdovae_constants.rs").write_text(
        HEADER.replace("dnn/{stem}_data.h and dnn/{stem}_data.c", "dnn/dred_rdovae_constants.h")
        + "\n" + "\n".join(consts(k)) + "\n")


main()
