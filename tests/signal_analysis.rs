//! The signal analysis follows libopus's (`src/analysis.c`, float build).
//!
//! The analysis of the speech fixture and of a synthetic voiced signal, run
//! frame by frame as the encoder runs it, against the values libopus 1.6.1
//! (float) computes for the same input in its encoder: tonality and its
//! slope, activity, the music probabilities, the activity probability, the
//! pitch ratio, the bandwidth and the leakage boosts, every tenth (or
//! twentieth) frame of the first three seconds. The two differ only by
//! floating-point rounding (FFT, summation order), well within the
//! tolerances.

