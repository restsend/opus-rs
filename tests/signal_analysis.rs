/// A voiced-speech-like signal (as in `issue_27_libopus_oracle.rs`): a
/// 140 Hz harmonic series with a slow pitch drift and a syllable-rate
/// envelope, whose harmonics give large leakage boosts.
fn voiced(sr: usize, n: usize) -> Vec<f32> {
    use std::f32::consts::PI;
    let mut phase = 0.0f32;
    (0..n)
        .map(|i| {
            let t = i as f32 / sr as f32;
            let f0 = 140.0 + 15.0 * (2.0 * PI * 0.7 * t).sin();
            phase += 2.0 * PI * f0 / sr as f32;
            let env = 0.6 + 0.4 * (2.0 * PI * 3.0 * t).sin();
            let l: f32 = (1..=8)
                .map(|h| 0.25 / h as f32 * (h as f32 * phase).sin())
                .sum();
            l * env * 0.5
        })
        .collect()
}

fn check(sr: usize, channels: usize, ms: usize, reference: &[Reference]) {
    let frame = sr * ms / 1000;
    let last = reference.last().unwrap().0;
    check_input(
        &vbr::speech(sr, channels, frame * (last + 1)),
        sr,
        channels,
        ms,
        reference,
    );
}

fn check_input(input: &[f32], sr: usize, channels: usize, ms: usize, reference: &[Reference]) {
    let frame = sr * ms / 1000;
    let last = reference.last().unwrap().0;
    let mut analysis = TonalityAnalysisState::new(sr as i32);
    let fft = default_mode().mdct.fft(0);
    let mut expected = reference.iter().peekable();
    for f in 0..=last {
        let pcm = &input[f * frame * channels..(f + 1) * frame * channels];
        let info = analysis.run(fft, AnalysisPcm::F32(pcm), frame, channels, 24);
        let Some(&(_, values, bandwidth, leak_boost)) = expected.next_if(|r| r.0 == f) else {
            continue;
        };
        let label = format!("{sr} Hz {channels} ch {ms} ms frame {f}");
        assert!(info.valid, "{label}: no analysis");
        let got = [
            info.tonality,
            info.tonality_slope,
            info.activity,
            info.music_prob,
            info.music_prob_min,
            info.music_prob_max,
            info.activity_probability,
            info.max_pitch_ratio,
        ];
        for (i, (g, e)) in got.iter().zip(values).enumerate() {
            let tolerance = if i == 1 { 0.02 } else { 0.01 };
            assert!(
                (g - e).abs() <= tolerance,
                "{label}: value {i} is {g}, libopus {e}"
            );
        }
        assert_eq!(info.bandwidth, bandwidth, "{label}: bandwidth");
        for (b, (&g, &e)) in info.leak_boost.iter().zip(&leak_boost).enumerate() {
            assert!(
                (i32::from(g) - i32::from(e)).abs() <= 2,
                "{label}: leak boost {b} is {g}, libopus {e}"
            );
        }
    }
}

